// ── 智慧動態靈感卡生成器 (當抽中任意資料庫自訂單字時，自動生成高品質卡片) ──
export const getOrGenerateWisdomCard = (rawWord) => {
  if (!rawWord) return WORD_WISDOM_DECK[0];

  const wordEn = (rawWord.en || rawWord.word || '').trim();
  const wordZh = (rawWord.zh || '').trim();

  // 1. 若在精選卡牌庫中，直接使用精選卡
  const match = WORD_WISDOM_DECK.find(
    c => c.word.toLowerCase() === wordEn.toLowerCase() || c.id === wordEn.toLowerCase()
  );
  if (match) return match;

  // 2. 若資料庫本身已有自訂的金句欄位
  if (rawWord.quote_en && rawWord.quote_zh) {
    return {
      id: wordEn.toLowerCase(),
      word: wordEn.charAt(0).toUpperCase() + wordEn.slice(1),
      phonetic: rawWord.phonetic || '',
      partOfSpeech: rawWord.part_of_speech || 'n. 單字',
      icon: rawWord.icon || '✨',
      energy: '每日智慧 (Wisdom)',
      theme: 'amber',
      quoteEn: rawWord.quote_en,
      quoteZh: rawWord.quote_zh
    };
  }

  // 3. 智慧範本生成器 (零缺漏，保證小學生讀得懂)
  const capitalized = wordEn.charAt(0).toUpperCase() + wordEn.slice(1);
  return {
    id: wordEn.toLowerCase(),
    word: capitalized,
    phonetic: '',
    partOfSpeech: `n. ${wordZh}`,
    icon: '✨',
    energy: '學習能量 (Growth)',
    theme: 'emerald',
    quoteEn: `Learn the word "${capitalized}" and practice it every day!`,
    quoteZh: `「${capitalized}（${wordZh}）」是你在英語冒險世界中獲得的一把新鑰匙！把它收在心中，試著用自信的聲音多讀三次。每一次開口練習，都在讓你變得更聰明、更有自信！今天就跟著這份正能量一起快樂學習吧！`
  };
};

// ── 隨機抽取 3 張卡牌供學生選取 ──
export const drawThreeCandidateCards = (customWordsPool = []) => {
  // 合併精選庫與傳入的自訂題庫
  const pool = [...WORD_WISDOM_DECK];

  if (Array.isArray(customWordsPool) && customWordsPool.length > 0) {
    customWordsPool.forEach(w => {
      const card = getOrGenerateWisdomCard(w);
      if (!pool.some(p => p.id === card.id)) {
        pool.push(card);
      }
    });
  }

  // 隨機打亂並取 3 張
  const shuffled = [...pool].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, 3);
};
